CREATE TABLE app_brand_artifacts (
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 build_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 brand_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 channel VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 package_name VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version_name VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version_code INT UNSIGNED NOT NULL,
 trial_protocol INT UNSIGNED NOT NULL DEFAULT 0,
 signer_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 apk_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 artifact_url VARCHAR(300) NOT NULL,
 verification_mac CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 KEY brand_artifact_channel(brand_id,channel,version_code),
 FOREIGN KEY(build_id) REFERENCES app_brand_builds(id),
 FOREIGN KEY(brand_id) REFERENCES app_brands(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE trial_offer_publications (
 tenant_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 brand_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 policy_stamp CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 daily_limit INT UNSIGNED NOT NULL,
 updated_by CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id),
 FOREIGN KEY(brand_id) REFERENCES app_brands(id),
 FOREIGN KEY(updated_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE trial_public_sessions (
 token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 operation_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 resume_operation_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 brand_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 device_ref CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 client_key TEXT NOT NULL,
 client_key_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash_mac CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 nonce_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 policy_stamp CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 ip_ref CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 expires_at DATETIME NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(brand_id) REFERENCES app_brands(id),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id),
 KEY trial_session_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE trial_signup_operations (
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 tenant_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 brand_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 session_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 eligibility_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL UNIQUE,
 client_key_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_cipher TEXT NULL,
 activation_cipher TEXT NULL,
 state VARCHAR(32) NOT NULL DEFAULT 'reserved',
 panel_line_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NULL,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 next_attempt_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 activation_until DATETIME NULL,
 contact_retention_until DATETIME NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(tenant_id) REFERENCES tenants(id),
 FOREIGN KEY(brand_id) REFERENCES app_brands(id),
 FOREIGN KEY(session_hash) REFERENCES trial_public_sessions(token_hash),
 KEY trial_operation_due(state,next_attempt_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE trial_signup_budgets (
 operation_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 panel_reseller_id VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 device_ref CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 ip_ref CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 counted BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(operation_id) REFERENCES trial_signup_operations(id),
 KEY trial_reseller_budget(panel_reseller_id,created_at,counted),
 KEY trial_device_budget(panel_reseller_id,device_ref,created_at,counted),
 KEY trial_ip_budget(ip_ref,created_at,counted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
